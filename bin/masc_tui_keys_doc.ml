(** The key reference document, rendered from the binding registry.

    [Masc_tui_keys] is the single source of truth for what a key does: the
    footer rows, the in-app [?] sheet and this document all read it, so a
    key cannot be explained two ways. The document is regenerated by
    [masc_tui_keys_doc_cli] and committed; [test_tui_keys_doc] fails when
    the committed copy and the registry disagree. *)

let cell text =
  (* A help sentence may name a pipe in a key pair ("y / n"); a bare pipe
     would cut the table cell. *)
  String.map (fun c -> if Char.equal c '|' then '/' else c) text

let section buf (title, rows) =
  Buffer.add_string buf ("\n## " ^ title ^ "\n\n");
  Buffer.add_string buf "| Keys | What it does |\n|---|---|\n";
  List.iter
    (fun (key, help) ->
      Buffer.add_string
        buf
        ("| `" ^ cell key ^ "` | " ^ cell help ^ " |\n"))
    rows

let markdown () =
  let buf = Buffer.create 8192 in
  Buffer.add_string buf
    "<!-- Generated by masc_tui_keys_doc.ml from bin/masc_tui_keys.ml. Do not \
     edit by hand. -->\n<!-- Regenerate: dune exec bin/masc_tui_keys_doc_cli.exe \
     > docs/guides/TUI-KEYS.md -->\n";
  Buffer.add_string buf
    "\n# TUI key reference\n\n\
     Press `?` in the TUI to read this sheet on screen; the surface you are\n\
     on is the first section there. Every footer row names `?:help` where the\n\
     key answers. In a chat, `?` opens the sheet only while the draft is\n\
     empty -- once a sentence has started it is an ordinary question mark.\n\
     The command palette is `:`.\n";
  List.iter (section buf) (Masc_tui_keys.help_sections ());
  Buffer.contents buf
